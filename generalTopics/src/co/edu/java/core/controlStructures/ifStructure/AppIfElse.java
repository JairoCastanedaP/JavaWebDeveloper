package co.edu.java.core.controlStructures.ifStructure;

public class AppIfElse {
    public static void main(String[] args) {

        int x=0;

        if (x > 0) {
            System.out.println("X ="+x+" es mayor que cero");
        } else {
            System.out.println("X ="+x+" es menor que cero");
        }
    }
}
